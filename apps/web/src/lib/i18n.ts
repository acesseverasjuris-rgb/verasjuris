export const MESSAGE_CATALOGS: Record<Locale, Catalog> = {
  "pt-BR": ptBR,
  "en-US": enUS,
  "es-ES": esES,
};

export const LOCALE_LABELS: Record<Locale, string> = {
  "pt-BR": "Português (Brasil)",
  "en-US": "English (US)",
  "es-ES": "Español",
};

export function isLocale(value: string | null | undefined): value is Locale {
  return SUPPORTED_LOCALES.includes(value as Locale);
}

export function normalizeLocale(value: string | null | undefined): Locale | null {
  if (!value) return null;
  if (isLocale(value)) return value;
  const lower = value.toLowerCase();
  if (lower.startsWith("pt")) return "pt-BR";
  if (lower.startsWith("en")) return "en-US";
  if (lower.startsWith("es")) return "es-ES";
  return null;
}

/** Resolução: user → org → browser → pt-BR */
export function resolveLocale(input: {
  userLocale?: string | null;
  orgLocale?: string | null;
  browserLocale?: string | null;
}): Locale {
  return (
    normalizeLocale(input.userLocale) ??
    normalizeLocale(input.orgLocale) ??
    normalizeLocale(input.browserLocale) ??
    DEFAULT_LOCALE
  );
}

export function translate(locale: Locale, key: string, fallback?: string): string {
  return MESSAGE_CATALOGS[locale][key] ?? MESSAGE_CATALOGS[DEFAULT_LOCALE][key] ?? fallback ?? key;
}

export function browserPreferredLocale(): string | null {
  if (typeof navigator === "undefined") return null;
  return navigator.languages?.[0] ?? navigator.language ?? null;
}
